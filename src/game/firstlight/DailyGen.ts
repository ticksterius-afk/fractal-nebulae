/**
 * The nebula rotation: dense and open, absorbing and reflecting alternate. The Cauliflower opens (#1).
 * Nebulae of the pool missing here are appended; ids missing from the pool are skipped.
 */
export const NEBULA_CYCLE: readonly string[] = (() => {
  const want = ['bulb', 'kleinian', 'menger', 'tree', 'julia', 'apollonian', 'box', 'sierpinski', 'kifs'];
  const pool: string[] = [];
  for (const a of DAILY_ARENAS) if (!pool.includes(a.nebula)) pool.push(a.nebula);
  return [...want.filter((n) => pool.includes(n)), ...pool.filter((n) => !want.includes(n))];
})();

/** Nebulae with dense regions (curated arenas with ≥ 65 % of chords blocked): the Sunday pool. */
export const SUNDAY_NEBULAE: readonly string[] = (() => {
  const dense = ['menger', 'bulb', 'julia', 'box', 'apollonian', 'kifs'].filter((n) => NEBULA_CYCLE.includes(n));
  return dense.length >= 3 ? dense : NEBULA_CYCLE;
})();

