/** Quaternion from axis (normalized internally) and angle in radians. */
function q(ax: number, ay: number, az: number, angle: number): [number, number, number, number] {
  const l = Math.hypot(ax, ay, az) || 1;
  const s = Math.sin(angle / 2) / l;
  return [ax * s, ay * s, az * s, Math.cos(angle / 2)];
}

