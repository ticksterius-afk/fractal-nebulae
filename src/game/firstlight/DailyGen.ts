const mod = (a: number, n: number): number => ((a % n) + n) % n;

/** UTC weekday of the epoch (Friday). */
const EPOCH_WEEKDAY = new Date(`${DAILY_EPOCH}T00:00:00Z`).getUTCDay();

/** Days since the epoch for a valid id ≥ the epoch, else −1. */
function dayOf(dateId: string): number {
  if (typeof dateId !== 'string') return -1;
  const d = daysBetween(DAILY_EPOCH, dateId);
  return Number.isFinite(d) && d >= 0 ? d : -1;
}

/** DAILY_ARENAS indices of a nebula, in pool order. */
function arenasOf(nebula: string): number[] {
  const out: number[] = [];
  for (let i = 0; i < DAILY_ARENAS.length; i++) if (DAILY_ARENAS[i].nebula === nebula) out.push(i);
  return out;
}

const cycleNebula = (d: number): string => NEBULA_CYCLE[mod(d, NEBULA_CYCLE.length)];

const densityCache = new Map<number, number>();

/**
 * Share of 48 random chords of arena `i`'s ball that hit structure (sphere tracing, contact at 3e-4 R):
 * how obstructed beams are. Deterministic (the stream is seeded by the arena itself), cached; a few ms
 * per arena, computed only for a Sunday's nebula.
 */
export function arenaDensity(i: number): number {
  const hit = densityCache.get(i);
  if (hit !== undefined) return hit;
  const a = DAILY_ARENAS[i];
  if (!a) return 0;
  const fractal = nebulaFractal(a.nebula);
  const params = frozenParams(a.nebula, a.clock);
  const iter = fractal.cpuIter;
  const de = (x: number, y: number, z: number): number => {
    const v = fractal.de(x, y, z, params, iter);
    return v === v ? v : 0;
  };
  const c = a.arena.centerLocal;
  const R = a.arena.radiusLocal;
  const eps = 3e-4 * R;
  const rng = mulberry32(fnv1a(`${a.nebula}:${a.clock}:${c[0]},${c[1]},${c[2]}:${R}:density`));
  const unit = (): Vec3 => {
    const z = 2 * rng() - 1;
    const t = 2 * Math.PI * rng();
    const s = Math.sqrt(Math.max(0, 1 - z * z));
    return [s * Math.cos(t), s * Math.sin(t), z];
  };
  const N = 48;
  let blocked = 0;
  for (let k = 0; k < N; k++) {
    const u = unit();
    const v = unit();
    const ax = c[0] + u[0] * R;
    const ay = c[1] + u[1] * R;
    const az = c[2] + u[2] * R;
    const dx = (v[0] - u[0]) * R;
    const dy = (v[1] - u[1]) * R;
    const dz = (v[2] - u[2]) * R;
    const L = Math.hypot(dx, dy, dz);
    if (!(L > eps)) continue;
    let t = 0;
    for (let s = 0; s < 4000 && t < L; s++) {
      const dd = de(ax + (dx * t) / L, ay + (dy * t) / L, az + (dz * t) / L);
      if (!(dd > eps)) {
        blocked++;
        break;
      }
      t += Math.max(0.8 * dd, eps);
    }
  }
  const out = blocked / N;
  densityCache.set(i, out);
  return out;
}

/** Weekday and nebula of day d ≥ 0 (cheap: no density measurement). */
function scheduleOf(d: number): { weekday: number; nebula: string } {
  const weekday = mod(EPOCH_WEEKDAY + d, 7);
  let nebula = cycleNebula(d);
  if (weekday === 0) {
    // A dense nebula, never Saturday's or Monday's (the cycle's), rotating by Sunday.
    const sunday = Math.floor(d / 7);
    for (let k = 0; k < SUNDAY_NEBULAE.length; k++) {
      const n = SUNDAY_NEBULAE[mod(sunday + k, SUNDAY_NEBULAE.length)];
      if (n !== cycleNebula(d - 1) && n !== cycleNebula(d + 1)) {
        nebula = n;
        break;
      }
    }
  }
  return { weekday, nebula };
}

/** The day's plan, or null for an invalid id or a day before #1. */
export function dailyPlan(dateId: string): DailyPlan | null {
  const d = dayOf(dateId);
  if (d < 0 || NEBULA_CYCLE.length === 0) return null;
  const { weekday, nebula } = scheduleOf(d);
  const { recipe, fallback } = DAILY_RECIPES[weekday];
  let arenas: number[];
  if (weekday === 0) {
    // Densest first (ties: pool order); the two densest alternate between visits.
    const sunday = Math.floor(d / 7);
    const ranked = arenasOf(nebula).sort((x, y) => arenaDensity(y) - arenaDensity(x) || x - y);
    const visit = Math.floor(sunday / SUNDAY_NEBULAE.length);
    if (ranked.length >= 2 && visit % 2 === 1) [ranked[0], ranked[1]] = [ranked[1], ranked[0]];
    arenas = ranked;
  } else {
    const list = arenasOf(nebula);
    const k = mod(Math.floor(d / NEBULA_CYCLE.length), list.length);
    arenas = [...list.slice(k), ...list.slice(0, k)];
  }
  return {
    dateId,
    day: d,
    number: dailyNumber(dateId),
    weekday,
    tier: recipe.tier,
    nebula,
    arenas,
    recipe,
    fallback,
    seed: dailySeed(dateId, 'firstlight'),
  };
}

function shortName(nebula: string): string {
  const name = NEBULAE.find((n) => n.id === nebula)?.name ?? nebula;
  return name
    .replace(/^The\s+/i, '')
    .replace(/\s+(Nebula|Lattice|Foam|Web|Veil|Pyramid|Kaleidoscope)$/i, '')
    .replace(/[’']s$/, '');
}

/** Number and nebula names for labels and share strings (cheap: no generation). */
export function dailyInfo(dateId: string): DailyInfo {
  const d = dayOf(dateId);
  // Not a daily (invalid or before #1): still a stable answer, never a throw.
  const nebula =
    NEBULA_CYCLE.length === 0 ? 'bulb' : d >= 0 ? scheduleOf(d).nebula : NEBULA_CYCLE[mod(dailySeed(String(dateId), 'firstlight'), NEBULA_CYCLE.length)];
  return { dateId, number: dailyNumber(dateId), nebula, nebulaShort: shortName(nebula) };
}

