/** Abandon a bundle request after this long (then generate). */
const FETCH_TIMEOUT_MS = 8000;
/** A month is ~50 KB; anything far larger is not ours. */
const MAX_BUNDLE_CHARS = 4_000_000;

const isRec = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);

/** The month file `{ [dateId]: LevelDef }`, or null on any failure (never throws). */
async function fetchBundle(url: string): Promise<Record<string, unknown> | null> {
  if (typeof fetch !== 'function') return null;
  // Without a document a relative URL resolves against nothing (Node tools): generate instead.
  if (typeof document === 'undefined' && !/^[a-z][a-z0-9+.-]*:/i.test(url)) return null;
  let timer: ReturnType<typeof setTimeout> | undefined;
  try {
    const ctl = typeof AbortController === 'function' ? new AbortController() : null;
    if (ctl) timer = setTimeout(() => ctl.abort(), FETCH_TIMEOUT_MS);
    const res = await fetch(url, ctl ? { signal: ctl.signal } : undefined);
    if (!res.ok) return null;
    const text = await res.text();
    // The Vite dev server answers a missing file with index.html (200): JSON.parse rejects it.
    if (text.length > MAX_BUNDLE_CHARS) return null;
    const data: unknown = JSON.parse(text);
    return isRec(data) ? data : null;
  } catch {
    return null;
  } finally {
    if (timer !== undefined) clearTimeout(timer);
  }
}

/** Month bundles by URL: in-flight and loaded ones are shared; failures are forgotten (retried next time). */
const bundles = new Map<string, Promise<Record<string, unknown> | null>>();

function monthBundle(url: string): Promise<Record<string, unknown> | null> {
  let p = bundles.get(url);
  if (!p) {
    p = fetchBundle(url).then((b) => {
      if (!b) bundles.delete(url);
      return b;
    });
    bundles.set(url, p);
  }
  return p;
}

/** Runtime generation for loadDaily's fallback: generateDaily, or the same code off the main thread. */
export type DailyGenerate = (dateId: string) => LevelDef | null | Promise<LevelDef | null>;

/**
 * The day's level: the pre-generated monthly bundle `${baseUrl}daily/firstlight/YYYY-MM.json` (relative
 * to the page by default) when it holds a valid entry for the day, else runtime generation by `generate`
 * (identical in Node / Chromium; the browser passes dailyClient.generateDailyAsync so the main thread
 * never blocks). null only for an invalid id or a day before #1.
 */
export async function loadDaily(dateId: string, baseUrl = '', generate: DailyGenerate = generateDaily): Promise<LevelDef | null> {
  if (dayOf(dateId) < 0) return null;
  const base = typeof baseUrl === 'string' ? baseUrl : '';
  const bundle = await monthBundle(`${base}daily/firstlight/${dateId.slice(0, 7)}.json`);
  if (bundle && Object.prototype.hasOwnProperty.call(bundle, dateId)) {
    const level = sanitizeLevel(bundle[dateId]);
    // The labels and the share string come from dailyInfo: a stale entry on another nebula is not used.
    if (level && level.id === `daily-${dateId}` && level.chapter === 'daily' && level.nebula === dailyInfo(dateId).nebula) return level;
  }
  // A level that crossed a worker boundary is re-sanitised (a no-op for generateDaily's canonical output).
  const level = await generate(dateId);
  return level ? sanitizeLevel(level) : null;
}
