/** 1 = Mon–Tue (one mass), 2 = Wed–Fri (two), 3 = Sat (three), 4 = Sun (two masses, harder arena). */
export type DailyTier = 1 | 2 | 3 | 4;

export interface DailyRecipe {
  tier: DailyTier;
  /** Generator budget, one entry per mass, in bend order. */
  masses: readonly MassSize[];
  /** Goal seeds (default: the Generator's, one per leg). */
  seedCount?: number;
  /** The unlensed beam passes the last seed within [lo, hi] × r (the "almost" moment). */
  almost?: readonly [number, number];
  /** Seed radius × R (default: the Generator's, 0.05). */
  seedRadius?: number;
  /** Generator attempts per try. */
  maxAttempts: number;
  /** Arenas of the nebula to try this recipe in (the scheduled one first). */
  arenas: number;
}

