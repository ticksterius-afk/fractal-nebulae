/**
 * First Light — the free daily puzzle (design/20-first-light.md §3.3, §7.4; design/60-first-light-build.md
 * §L "DailyGen").
 *
 * One puzzle per UTC day, the same for everyone, deterministic from the date alone (no Math.random, no
 * wall time: the Generator and the gates count evaluations). No DOM except loadDaily's optional fetch,
 * and three.js maths only through the Generator's reach code (Reach.ts), so the Node tools share every line.
 *
 * Schedule (d = days since DAILY_EPOCH 2026-10-02 = #1, weekday in UTC):
 *  - Nebula: NEBULA_CYCLE[d mod 9] (dense / open and absorbing / reflecting alternate), so consecutive
 *    days always differ. Sundays swap in a nebula with dense regions (SUNDAY_NEBULAE, rotating, never
 *    Saturday's or Monday's).
 *  - Arena: that nebula's DAILY_ARENAS in turn (its k-th appearance uses arena k mod n). Sundays take
 *    the harder arenas: the densest of the nebula by `arenaDensity` (the share of random chords of
 *    the ball that hit structure, measured once per arena and cached), the two densest alternating.
 *  - Recipe by weekday (DAILY_RECIPES): Mon one medium mass with an "almost" seed (the unlensed beam
 *    passes it within 3–8 r); Tue one mass, two seeds on one bent leg; Wed two medium; Thu two heavy;
 *    Fri a light and a heavy (which goes where?); Sat three heavy (equal sizes: mixed three-mass budgets
 *    fail the minimal gate) with seeds of 4 % R; Sun two medium and three seeds in a harder arena.
 *    Tiers: 1 = Mon–Tue, 2 = Wed–Fri, 3 = Sat, 4 = Sun.
 *  - Clickable: every daily is generated with the Generator's `reach` option — its masses authored where
 *    the click aimed beside the beam lands from the vantage, and the quick reach gate passed (each mass
 *    one-click reachable with ≥ 400 px² at 1280×720, the click aimed at it solving at 60°, 70° and 100°),
 *    the rule tools/fl-reach.ts audits the bundles with.
 *  - Seed: dailySeed(dateId, 'firstlight'); the Generator retries with its own sub-seeds (maxAttempts).
 *    When a recipe fails it is tried in the nebula's next arena(s) with sub-seed hash2(seed, step) (two
 *    for Mon–Tue, three of the densest for Sun, all of them for Wed–Sat), then the easier recipes of
 *    `fallback` follow (Sat: three medium before two masses), and last a plain one-mass level in every
 *    arena of the nebula, then of the pool. A valid date ≥ DAILY_EPOCH never yields null in practice
 *    (one-mass levels succeed in 64/64 arena × seed runs); tools/fl-daily-build.ts proves it for the
 *    bundled window.
 *  - The level: id `daily-<date>` (the gates' seed, so tools/fl-check reproduces the verdict), chapter
 *    "daily", index = the daily number, name "Daily #N", hints and teach line written from the solution
 *    trace (bends, S-turns, sizes, reflections, close passes; seeds are named by path order).
 *
 * Delivery: tools/fl-daily-build.ts writes public/daily/firstlight/YYYY-MM.json ({ [dateId]: LevelDef },
 * one level per line) for DAILY_WINDOW_DAYS days from the epoch, each generated by generateDaily and
 * fully gated. loadDaily fetches `${baseUrl}daily/firstlight/YYYY-MM.json` (relative to the page: with
 * Vite's base './' that works in dev, in dist/ and under any sub-path), sanitises the day's entry and
 * caches the month; on any failure (no fetch, offline, 404, the dev server's HTML fallback, a bad entry)
 * it generates the same level at runtime. The bundle exists so every browser shows the same bits (other
 * engines may differ in the last bit of Math.pow inside the DEs) and so nobody waits for the generator.
 * Runtime generation cost (Node, one core, all 400 bundled days, fl-daily-check --all --jobs 1), p50 / p95 /
 * max: tier 1 0.02 / 0.06 / 0.09 s, tier 2 0.19 / 0.63 / 1.7 s, tier 4 0.20 / 0.93 / 1.1 s, tier 3 (three
 * heavy masses) 2.0 / 9.8 / 16.6 s. generateDaily itself is synchronous, so the browser passes loadDaily
 * dailyClient.generateDailyAsync, which runs this same generateDaily in a module worker (dailyWorker.ts):
 * the page keeps animating and the level is bit-identical. This module stays Worker-free for the tools.
 * Window build (2026-10-02 … 2027-11-05): 32 of 400 days needed a fallback step (18 Wed–Fri, 12 Saturdays,
 * 2 Sundays), each solved by its own recipe in another arena of its nebula: no day dropped a tier or
 * changed its budget (one Saturday has two seeds instead of three, which its recipe allows).
 *
 * Public API:
 *   loadDaily(dateId, baseUrl = '', generate = generateDaily) → Promise<LevelDef | null>
 *                                                                bundle first, else generate(dateId)
 *   generateDaily(dateId) → LevelDef | null                      deterministic, memoised (returns a copy)
 *   dailyInfo(dateId) → DailyInfo                                number + nebula names (no generation)
 *   dailyPlan(dateId) → DailyPlan | null                         weekday, tier, nebula, arena, recipe
 *   generateDailyReport(dateId) → DailyReport                    generation with diagnostics (tools)
 *   DAILY_RECIPES, DAILY_WINDOW_DAYS, NEBULA_CYCLE, SUNDAY_NEBULAE, arenaDensity(i)
 */
