/** Generates the day's level with diagnostics (not memoised; tools use it). */
export function generateDailyReport(dateId: string): DailyReport {
  const t0 = performance.now();
  const plan = dailyPlan(dateId);
  const rep: DailyReport = { dateId, plan, level: null, recipe: null, arena: -1, step: 0, attempts: 0, evals: 0, ms: 0, gates: null, features: null };
  if (!plan) return rep;
  // Tries: the recipe in its arenas, the easier recipes in theirs, then one plain mass anywhere.
  const tries: { recipe: DailyRecipe; arena: number }[] = [];
  for (const r of [plan.recipe, ...plan.fallback]) {
    for (let k = 0; k < Math.min(r.arenas, plan.arenas.length); k++) tries.push({ recipe: r, arena: plan.arenas[k] });
  }
  for (const a of plan.arenas) tries.push({ recipe: PLAIN, arena: a });
  for (let a = 0; a < DAILY_ARENAS.length; a++) if (!plan.arenas.includes(a)) tries.push({ recipe: PLAIN, arena: a });

  const id = `daily-${dateId}`;
  for (let step = 0; step < tries.length; step++) {
    const { recipe, arena } = tries[step];
    const da = DAILY_ARENAS[arena];
    const g = generateLevel({
      nebula: da.nebula,
      clock: da.clock,
      arena: da.arena,
      masses: recipe.masses,
      seed: step === 0 ? plan.seed : hash2(plan.seed, step),
      seedCount: recipe.seedCount,
      seedRadius: recipe.seedRadius,
      almost: recipe.almost,
      maxAttempts: recipe.maxAttempts,
      // Every daily is click-reachable from its vantage (Reach.quickReach, the game's placement code).
      reach: true,
      id,
      chapter: 'daily',
      index: Math.max(1, plan.number),
      name: `Daily #${plan.number}`,
    });
    rep.attempts += g.attempts;
    rep.evals += g.evals;
    if (!g.level) continue;
    // Texts never feed the gates (only geometry and the id do): the verdict stands.
    const d = describe(g.level);
    rep.level = sanitizeLevel({ ...g.level, hints: d.hints, teach: d.teach, hintMass: d.hintMass }) ?? g.level;
    rep.recipe = recipe;
    rep.arena = arena;
    rep.step = step;
    rep.gates = g.report;
    rep.features = d.features;
    break;
  }
  rep.ms = performance.now() - t0;
  return rep;
}

const generated = new Map<string, LevelDef | null>();

/** A deep copy (levels are plain JSON data). */
const copyLevel = (l: LevelDef): LevelDef => JSON.parse(JSON.stringify(l)) as LevelDef;

/**
 * The day's level, generated deterministically at runtime (the bundles are built from exactly this).
 * Memoised per date; returns a fresh copy. null for an invalid id or a day before #1.
 */
export function generateDaily(dateId: string): LevelDef | null {
  let level = generated.get(dateId);
  if (level === undefined) {
    level = generateDailyReport(dateId).level;
    if (dayOf(dateId) >= 0) generated.set(dateId, level);
  }
  return level ? copyLevel(level) : null;
}

