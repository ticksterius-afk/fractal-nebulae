interface Along {
  s: number;
  d: number;
  p: Vec3;
  t: Vec3;
}

/** Closest point of a beam polyline to q: path length, distance, the point and the segment's direction. */
function nearestOn(b: Beam, q: Readonly<Vec3>): Along {
  const P = b.points;
  const n = P.length / 3;
  let best: Along = { s: 0, d: Infinity, p: [P[0], P[1], P[2]], t: [0, 0, 1] };
  for (let i = 0; i + 1 < n; i++) {
    const ax = P[3 * i];
    const ay = P[3 * i + 1];
    const az = P[3 * i + 2];
    const ux = P[3 * i + 3] - ax;
    const uy = P[3 * i + 4] - ay;
    const uz = P[3 * i + 5] - az;
    const uu = ux * ux + uy * uy + uz * uz;
    let f = uu > 0 ? ((q[0] - ax) * ux + (q[1] - ay) * uy + (q[2] - az) * uz) / uu : 0;
    f = f < 0 ? 0 : f > 1 ? 1 : f;
    const p: Vec3 = [ax + f * ux, ay + f * uy, az + f * uz];
    const d = Math.hypot(p[0] - q[0], p[1] - q[1], p[2] - q[2]);
    if (d < best.d) {
      const l = Math.sqrt(uu) || 1;
      best = { s: b.length[i] + f * (b.length[i + 1] - b.length[i]), d, p, t: [ux / l, uy / l, uz / l] };
    }
  }
  return best;
}

const ORDINAL = ['first', 'second', 'third', 'fourth', 'fifth', 'sixth'];
const ordinal = (i: number): string => ORDINAL[i] ?? `#${i + 1}`;

/** "close to the star" / "about a third of the way along the star's beam". */
function alongWords(f: number): string {
  if (!(f >= 0.18)) return 'close to the star';
  const w =
    f < 0.29 ? 'about a quarter of the way' : f < 0.42 ? 'about a third of the way' : f < 0.58 ? 'about halfway' : f < 0.71 ? 'about two-thirds of the way' : f < 0.85 ? 'about three-quarters of the way' : 'near the far end';
  return `${w} along the star's beam`;
}

/**
 * Where a mass sits relative to the beam it bends, in shadow widths (the drawn shadow is the capture
 * disc, radius 2.6 ρ): "a shadow-width from the beam", "with its shadow just clear of the new beam".
 */
function offsetWords(rhoUnits: number, beam: string): string {
  const w = rhoUnits / (2 * CRITICAL_IMPACT);
  if (!(w >= 0.75)) return `with its shadow just clear of the ${beam}`;
  const n = w < 1.25 ? 'a shadow-width' : w < 1.75 ? 'one and a half shadow-widths' : w < 2.5 ? 'two shadow-widths' : 'three shadow-widths';
  return `${n} from the ${beam}`;
}

/**
 * Closest pass (× ρ) that earns the capture remarks: within 1.4 × the critical impact parameter (2.6 ρ)
 * a small misplacement swallows the beam.
 */
const CLOSE_PASS = 3.6;

/** Closest passes (× ρ) within this factor of each other make turns "about as sharp". */
const SHARPER = 1.1;

const SIZE_RANK: Readonly<Record<MassSize, number>> = { light: 0, medium: 1, heavy: 2 };

/**
 * Which size makes the sharper turn in a mixed budget, from the solution trace (`q` = closest pass × that
 * mass's own ρ). The turn depends only on q (α ≈ 2ρ/b), so a light mass hugging the beam out-turns a
 * heavy one passed wide: about half the Friday solutions do exactly that. "" when the trace is unusable.
 */
function sharperWords(bends: readonly { size: MassSize; q: number }[]): string {
  if (bends.length < 2) return '';
  let hi = bends[0].size;
  let lo = hi;
  for (const b of bends) {
    if (SIZE_RANK[b.size] > SIZE_RANK[hi]) hi = b.size;
    if (SIZE_RANK[b.size] < SIZE_RANK[lo]) lo = b.size;
  }
  let qHi = Infinity;
  let qLo = Infinity;
  for (const b of bends) {
    if (b.size === hi) qHi = Math.min(qHi, b.q);
    if (b.size === lo) qLo = Math.min(qLo, b.q);
  }
  if (hi === lo || !(qHi > 0 && qHi < Infinity && qLo > 0 && qLo < Infinity)) return '';
  if (qHi * SHARPER < qLo) return `The ${hi} mass makes the sharper turn.`;
  if (qLo * SHARPER < qHi) return `The ${lo} mass makes the sharper turn: it sits closer to the beam.`;
  return `${bends.length === 2 ? 'Both turns' : 'The turns'} are about as sharp: the ${hi} mass sits farther from the beam.`;
}

