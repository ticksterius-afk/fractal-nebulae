function describe(level: LevelDef): { hints: [string, string, string]; teach: string; hintMass: number; features: DailyFeatures } {
  const world = makeTraceWorld(level);
  const sol = level.solution.map((m) => placedMass(level, m.size, m.pos));
  const solved: TraceResult = traceLevel(level, world, sol);
  const unlensed: TraceResult = traceLevel(level, world, []);
  const beam = solved.beams[0];
  const goals = level.seeds.filter((s) => s.goal);
  const seedS = goals.map((s) => nearestOn(beam, s.pos).s).sort((a, b) => a - b);
  const lastSeed = seedS.length ? seedS[seedS.length - 1] : Infinity;
  const bends = sol.map((m, i) => ({ i, size: m.size, at: nearestOn(beam, m.pos), rho: m.rho, pos: m.pos })).sort((a, b) => a.at.s - b.at.s);
  // Opposite turns: the side (beam → mass) of bend j made ⟂ to the beam at bend j+1, against its side.
  const side = (b: (typeof bends)[number]): Vec3 => {
    const v: Vec3 = [b.pos[0] - b.at.p[0], b.pos[1] - b.at.p[1], b.pos[2] - b.at.p[2]];
    const l = Math.hypot(v[0], v[1], v[2]) || 1;
    return [v[0] / l, v[1] / l, v[2] / l];
  };
  let reflections = 0;
  const rp = beam.reflections;
  const reflS: number[] = [];
  for (let i = 0; i < rp.length; i += 3) reflS.push(nearestOn(beam, [rp[i], rp[i + 1], rp[i + 2]]).s);
  for (const s of reflS) if (s < lastSeed) reflections++;
  // A bounce between two bends mirrors the beam, so comparing their sides across it says nothing about how
  // the turns look (2026-11-21, 2027-01-23, 2027-07-31 read "back" where the vantage sees the same sense
  // again): such a bend is neither "back" nor "again" and no S.
  const bounced = bends.map((b, j) => j > 0 && reflS.some((s) => s > bends[j - 1].at.s && s < b.at.s));
  const opposite: boolean[] = bends.map(() => false);
  for (let j = 1; j < bends.length; j++) {
    if (bounced[j]) continue;
    const a = side(bends[j - 1]);
    const t = bends[j].at.t;
    const k = a[0] * t[0] + a[1] * t[1] + a[2] * t[2];
    const ap: Vec3 = [a[0] - k * t[0], a[1] - k * t[1], a[2] - k * t[2]];
    const b = side(bends[j]);
    opposite[j] = ap[0] * b[0] + ap[1] * b[1] + ap[2] * b[2] < -0.2 * (Math.hypot(ap[0], ap[1], ap[2]) || 1);
  }
  const closest = solved.massClosest.length ? Math.min(...solved.massClosest) : Infinity;
  let almost = Infinity;
  for (const s of goals) {
    const st = unlensed.seeds[s.id];
    if (st) almost = Math.min(almost, st.closest / s.radius);
  }
  const ub = unlensed.beams[0];
  const uLen = ub.length[ub.length.length - 1];
  const firstAlong = bends.length && uLen > 0 ? Math.min(1, bends[0].at.s / uLen) : 0;
  const k = sol.length;
  const sizes = bends.map((b) => b.size);
  const mixed = new Set(sizes).size > 1;
  const sBends = opposite.filter(Boolean).length;
  const features: DailyFeatures = { masses: k, seeds: goals.length, sizes, reflections, sBends, closest, almost, firstAlong };

  // Hint 1: the easier deduction.
  let h1: string;
  if (k === 1 && goals.length === 1) {
    h1 = almost <= 8 ? 'The beam already passes close to the seed. One mass beside it can pull it across.' : 'Light bends toward a mass. Put one beside the beam, on the side where the seed lies.';
  } else if (k === 1) {
    h1 = 'After a bend the light runs straight again. Make that new line pass through every seed.';
  } else if (k === 2 && sBends > 0) {
    h1 =
      fnv1a(`${level.id}:h1`) % 2 === 0
        ? 'No single bend reaches every seed: the beam must turn one way, then back the other.'
        : 'A mass only pulls the beam toward itself. These seeds need a turn one way, then a turn back.';
  } else if (k === 2) {
    h1 = 'The beam must turn twice: one mass for each turn, each beside the beam it bends.';
  } else {
    h1 = `The beam must turn ${COUNT_WORDS[k] ?? `${k} times`}, one mass per turn. Bend it onto the seeds in the order it reaches them.`;
  }
  const sharper = mixed ? sharperWords(bends.map((b) => ({ size: b.size, q: solved.massClosest[b.i] }))) : '';
  if (sharper) h1 += ` ${sharper}`;
  const pearls = level.nebula === 'apollonian';
  if (reflections > 0) h1 += ` ${pearls ? 'Pearl walls' : "The web's walls"} are mirrors: follow the light past its bounce.`;

  // Hint 2: the region (the HUD draws a dashed sphere around solution[hintMass] = the first bend).
  const h2 = `The marked sphere holds ${k === 1 ? 'the' : 'the first'} mass, ${alongWords(firstAlong)}.`;

  // Hint 3: the designer's note, the full solution in words.
  const target = (j: number): string => {
    const lo = bends[j].at.s;
    const hi = j + 1 < bends.length ? bends[j + 1].at.s : Infinity;
    const lit = seedS.filter((s) => s > lo && s <= hi).length;
    const before = seedS.filter((s) => s <= lo).length;
    if (lit === 0) return j + 1 < bends.length ? `toward the ${ordinal(j + 1)} mass` : 'into place';
    if (j === bends.length - 1) {
      if (lit === goals.length) return lit === 1 ? 'onto the seed' : 'through every seed';
      return lit === 1 ? 'onto the last seed' : lit === 2 ? 'through the last two seeds' : 'through the last seeds';
    }
    return lit === 1 ? `onto the ${ordinal(before)} seed` : lit === 2 ? `through the ${ordinal(before)} and ${ordinal(before + 1)} seeds` : 'through the next seeds';
  };
  // Compact wording (for three-mass notes that would overflow): the first mass "in the marked sphere"
  // (hint 2 already said where it is) instead of the along-the-beam words, "beam" for "new beam".
  const bendPart = (j: number, compact: boolean): string => {
    const b = bends[j];
    if (j === 0) {
      const where = compact ? 'in the marked sphere' : alongWords(firstAlong);
      return `A ${b.size} mass ${offsetWords(solved.massClosest[b.i], 'beam')}, ${where}, turns it ${target(0)}.`;
    }
    const before = seedS.filter((s) => s <= b.at.s).length;
    const where = before > 0 ? `just past the ${ordinal(before - 1)} seed` : 'before the first seed';
    return `Then a ${b.size} mass ${offsetWords(solved.massClosest[b.i], compact ? 'beam' : 'new beam')}, ${where}, turns it ${bounced[j] ? '' : opposite[j] ? 'back ' : 'again '}${target(j)}.`;
  };
  const remarks: string[] = [];
  if (reflections > 0) {
    const walls = pearls ? (reflections === 1 ? 'a pearl wall' : 'pearl walls') : reflections === 1 ? 'a wall of the web' : 'walls of the web';
    remarks.push(`It bounces off ${walls} on the way.`);
  }
  if (closest <= CLOSE_PASS) remarks.push('Keep the beam out of every shadow: light that crosses one is swallowed.');
  const note = (compact: boolean, nBends: number, nRemarks: number): string =>
    [...bends.slice(0, nBends).map((_, j) => bendPart(j, compact)), ...remarks.slice(0, nRemarks)].join(' ');
  // Never longer than the sanitiser allows, and every bend kept as long as possible: with all remarks,
  // then fewer, each in full and then compact wording; only then are the later bends dropped.
  const maxLen = LEVEL_LIMITS.maxHintLength;
  let h3 = '';
  for (let r = remarks.length; r >= 0 && !(h3.length > 0 && h3.length <= maxLen); r--) {
    h3 = note(false, bends.length, r);
    if (h3.length > maxLen) h3 = note(true, bends.length, r);
  }
  for (let n = bends.length - 1; h3.length > maxLen && n >= 1; n--) h3 = note(true, n, 0);
  if (h3.length > maxLen) h3 = h3.slice(0, maxLen - 1) + '…';

  // The one true thing the level shows (≤ 90 chars), most specific first; the variant by the level id.
  const lines =
    reflections > 0
      ? k === 1
        ? pearls ? TEACH.corner : TEACH.cornerWeb
        : pearls ? TEACH.bounce : TEACH.bounceWeb
      : closest <= CLOSE_PASS
        ? TEACH.close
        : mixed
          ? TEACH.mixed
          : k === 1 && goals.length > 1
            ? TEACH.line
            : k === 1
              ? TEACH.bend
              : k === 2 && sBends > 0
                ? TEACH.s
                : k === 2
                  ? TEACH.series
                  : TEACH.compose;
  const teach = lines[fnv1a(level.id) % lines.length];
  return { hints: [h1, h2, h3], teach, hintMass: bends.length ? bends[0].i : 0, features };
}

